"""Помилки під час створення компонентів (main -> create_*).

TemporaryError — тимчасова: рука ще не відповідає, камера не готова. main повторює спробу
startup.retries разів з паузою startup.retry_delay_s, потім зупиняється.
FatalError — повторювати немає сенсу: немає файла, кривий конфіг, компонент не реалізовано.
main зупиняється одразу з цим повідомленням.
"""


class TemporaryError(RuntimeError):
    """Тимчасова помилка: варто спробувати ще раз."""


class FatalError(RuntimeError):
    """Фатальна помилка: повтор не допоможе."""
